#!/usr/bin/env bash
# Build the Qt application and SDL3 renderer, then launch STARS.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

DO_RUN=1
BUILD_TYPE="${STARS_BUILD_TYPE:-Release}"
BUILD_DIR="${STARS_BUILD_DIR:-build}"

while [[ $# -gt 0 ]]; do
    case "$1" in
        --build-only|--no-run)
            DO_RUN=0
            ;;
        --debug)
            BUILD_TYPE=Debug
            ;;
        --help|-h)
            cat <<'EOF'
Usage: ./build.sh [options]

Build STARS and its renderer, then launch the application.

Options:
  --build-only  Build without launching STARS
  --no-run      Alias for --build-only
  --debug       Build with debug symbols instead of Release
  --help        Show this help

Environment:
  STARS_BUILD_DIR             Build directory (default: build; relative to repo)
  STARS_BUILD_TYPE            CMake configuration (default: Release)
  CMAKE_BUILD_PARALLEL_LEVEL  Maximum parallel build jobs (default: 4)
  CMAKE_PREFIX_PATH          Additional dependency prefixes, e.g. a Qt installation

Requires CMake, a C++20 compiler, zlib, and Qt 6.5+ with Widgets, Svg, Network, Concurrent, and ShaderTools.
SDL3 and Zstandard are fetched automatically if not installed.
On macOS, CMake also produces the stars.app bundle in the build directory.
EOF
            exit 0
            ;;
        *)
            echo "Unknown option: $1 (see --help)" >&2
            exit 2
            ;;
    esac
    shift
done

if ! command -v cmake >/dev/null 2>&1; then
    echo "CMake is required to build STARS." >&2
    exit 1
fi

echo "[build] Configuring STARS ($BUILD_TYPE)..." >&2
cmake -S . -B "$BUILD_DIR" \
    -DCMAKE_BUILD_TYPE="$BUILD_TYPE" \
    -DSTARS_UI=ON \
    -DSTARS_GPU=ON

echo "[build] Building application and renderer..." >&2
BUILD_ARGS=(--config "$BUILD_TYPE" --target stars stars_renderer)
if [[ -z "${CMAKE_BUILD_PARALLEL_LEVEL:-}" ]]; then
    BUILD_ARGS+=(--parallel 4)
fi
cmake --build "$BUILD_DIR" "${BUILD_ARGS[@]}"

# Generated by CMake, including the configuration subdirectory and .app/.exe
# layout where applicable. Avoid guessing generator-specific output paths.
IFS= read -r APP < "$BUILD_DIR/stars-$BUILD_TYPE.path"
if [[ ! -f "$APP" ]]; then
    echo "Built application not found: $APP" >&2
    exit 1
fi

if [[ "$DO_RUN" -eq 1 ]]; then
    echo "[run] Launching STARS..." >&2
    exec "$APP"
fi
echo "[done] Build complete: $APP" >&2
